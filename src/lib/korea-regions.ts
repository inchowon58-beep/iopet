export function canonicalSido(raw: string): string | null {
  const name = decodeURIComponent(raw || "").trim();
  if (!name) return null;
  if (SIDOS.includes(name)) return name;
  return SIDO_ALIASES[name] || null;
}

export function shortSidoName(official: string): string | undefined {
  return SIDO_SHORT[official];
}

/** 칩·사이트맵용: 서울특별시 다음에 서울 */
export function sidoChipNames(excludeOfficial?: string): string[] {
  const out: string[] = [];
  for (const s of SIDOS) {
    if (excludeOfficial && s === excludeOfficial) continue;
    out.push(s);
    const short = SIDO_SHORT[s];
    if (short) out.push(short);
  }
  return out;
}

export function parseSidoName(raw: string): string | null {
  return canonicalSido(raw);
}

export function isSidoName(raw: string): boolean {
  return Boolean(parseSidoName(raw));
}

const BY_KEY = new Map(KOREA_REGIONS.map((r) => [regionKey(r.sido, r.sigungu), r]));
const BY_SIDO = new Map<string, KoreaSigungu[]>();
for (const r of KOREA_REGIONS) {
  const list = BY_SIDO.get(r.sido) || [];
  list.push(r);
  BY_SIDO.set(r.sido, list);
}

export function getSigungu(sido: string, sigungu: string): KoreaSigungu | undefined {
  const official = canonicalSido(sido) || sido;
  return BY_KEY.get(regionKey(official, sigungu));
}

export function getSigunguByKey(key: string): KoreaSigungu | undefined {
  const parsed = parseRegionKey(key);
  if (!parsed) return undefined;
  return getSigungu(parsed.sido, parsed.sigungu);
}

export function getSigungus(sido: string): KoreaSigungu[] {
  const official = canonicalSido(sido) || sido;
  return BY_SIDO.get(official) || [];
}

export function getDongs(sido: string, sigungu: string): string[] {
  return getSigungu(sido, sigungu)?.dongs || [];
}

export function isValidDong(sido: string, sigungu: string, dong: string): boolean {
  const name = decodeURIComponent(dong || "").trim();
  return getDongs(sido, sigungu).includes(name);
}

export function neighborSigungus(sido: string, sigungu: string, count = 8): KoreaSigungu[] {
  const all = getSigungus(sido);
  const idx = all.findIndex((r) => r.sigungu === sigungu);
  if (idx < 0) return all.slice(0, count);
  const out: KoreaSigungu[] = [];
  for (let i = 1; i < all.length && out.length < count; i++) {
    out.push(all[(idx + i) % all.length]);
  }
  return out;
}

export function neighborDongs(sido: string, sigungu: string, dong: string, count = 6): string[] {
  const all = getDongs(sido, sigungu);
  const name = decodeURIComponent(dong || "").trim();
  return all.filter((d) => d !== name).slice(0, count);
}

export function areaLabel(sido: string, sigungu?: string, dong?: string): string {
  return [sido, sigungu, dong].filter(Boolean).join(" ");
}

