export type KoreaSigungu = {
  sido: string;
  sigungu: string;
  dongs: string[];
};

export function regionKey(sido: string, sigungu: string): string {
  return `${sido}_${sigungu}`;
}

export function parseRegionKey(raw: string): { sido: string; sigungu: string } | null {
  const decoded = decodeURIComponent(raw || "").trim();
  const i = decoded.indexOf("_");
  if (i <= 0 || i === decoded.length - 1) return null;
  return { sido: decoded.slice(0, i), sigungu: decoded.slice(i + 1) };
}

